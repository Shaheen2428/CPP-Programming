#include<iostream>
using namespace std;
int main(){
    int a,b;
    cout<<"Enter the number a: ";
    cin>>a;
    cout<<"Enter the number b: ";
    cin>>b;
    
    // Equal to Operator(==)
    if(a==b){
        cout<<"Yes"<<endl;
    }else{
        cout<<"No"<<endl;
    }

    // greater than Operator(>)
    if(a>b){
        cout<<"Yes"<<endl;
    }else{
        cout<<"No"<<endl;
    }


    // Less than Operator(<)
    if(a<b){
        cout<<"Yes"<<endl;
    }else{
        cout<<"No"<<endl;
    }


    // Less than or Equal to Operator(<=)
    if(a<=b){
        cout<<"Yes"<<endl;
    }else{
        cout<<"No"<<endl;
    }


    // greater than  or equal to Operator(>=)
    if(a>=b){
        cout<<"Yes"<<endl;
    }else{
        cout<<"No"<<endl;
    }

    //  Not Equal to Operator(!=)
    if(a!=b){
        cout<<"Yes"<<endl;
    }else{
        cout<<"No"<<endl;
    }

    


}